#!/usr/bin/env python3
"""Render resources/settings/settings.xml from the Translations.mc catalog.

Garmin Connect only accepts numeric ``listEntry`` values, so language and
translation are stored as catalog positions. Generating the file keeps those
positions in sync with ``source/Translations.mc`` instead of hand-maintaining
~60 indices. Run with ``--check`` in CI to verify the committed file.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))

from dailyverse_lib.catalog import (  # noqa: E402
    extract_catalog,
    extract_language_ids,
    setting_code_index,
    setting_codes,
)

SETTINGS_PATH = ROOT / "resources" / "settings" / "settings.xml"

HEADER = """<settings>
    <setting propertyKey="@Properties.appVersion" title="@Strings.SettingAppVersion">
        <settingConfig type="alphaNumeric" readonly="true" />
    </setting>

    <!-- Generated by tools/gen_settings.py - do not edit by hand.
         Garmin Connect list settings require numeric values, so the entries below
         are catalog positions from source/Translations.mc. -->
"""

FOOTER = """
    <setting propertyKey="@Properties.slot1Enabled" title="@Strings.SettingSlot1Enabled">
        <settingConfig type="boolean" />
    </setting>
    <setting propertyKey="@Properties.slot1Hour" title="@Strings.SettingSlot1Hour">
        <settingConfig type="numeric" min="0" max="23" />
    </setting>
    <setting propertyKey="@Properties.slot1Minute" title="@Strings.SettingSlot1Minute">
        <settingConfig type="numeric" min="0" max="59" />
    </setting>

    <setting propertyKey="@Properties.slot2Enabled" title="@Strings.SettingSlot2Enabled">
        <settingConfig type="boolean" />
    </setting>
    <setting propertyKey="@Properties.slot2Hour" title="@Strings.SettingSlot2Hour">
        <settingConfig type="numeric" min="0" max="23" />
    </setting>
    <setting propertyKey="@Properties.slot2Minute" title="@Strings.SettingSlot2Minute">
        <settingConfig type="numeric" min="0" max="59" />
    </setting>

    <setting propertyKey="@Properties.slot3Enabled" title="@Strings.SettingSlot3Enabled">
        <settingConfig type="boolean" />
    </setting>
    <setting propertyKey="@Properties.slot3Hour" title="@Strings.SettingSlot3Hour">
        <settingConfig type="numeric" min="0" max="23" />
    </setting>
    <setting propertyKey="@Properties.slot3Minute" title="@Strings.SettingSlot3Minute">
        <settingConfig type="numeric" min="0" max="59" />
    </setting>
</settings>
"""

# Display labels for translation codes, mirroring Translations.codeDisplayName.
SPECIAL_LABELS = {"neu": "NeÜ", "nvi_pt": "NVI_PT"}


def code_label(code: str) -> str:
    return SPECIAL_LABELS.get(code, code.upper())


def render() -> str:
    languages = extract_language_ids()
    catalog = extract_catalog()
    codes = setting_codes(catalog)

    out = [HEADER]
    out.append('    <setting propertyKey="@Properties.languageIndex" title="@Strings.SettingLanguage">\n')
    out.append('        <settingConfig type="list">\n')
    for index, lang in enumerate(languages):
        out.append(f'            <listEntry value="{index}">@Strings.Lang_{lang}</listEntry>\n')
    out.append("        </settingConfig>\n")
    out.append("    </setting>\n\n")

    out.append('    <setting propertyKey="@Properties.translationIndex" title="@Strings.SettingTranslation">\n')
    out.append('        <settingConfig type="list">\n')
    out.append('            <listEntry value="0">@Strings.TranslationRandom</listEntry>\n')
    for lang in languages:
        for code in catalog[lang]:
            index = setting_code_index(code, catalog)
            out.append(f'            <listEntry value="{index}">{code_label(code)}</listEntry>\n')
    out.append("        </settingConfig>\n")
    out.append("    </setting>\n")

    assert len(codes) == sum(len(catalog[lang]) for lang in languages) + 1
    out.append(FOOTER)
    return "".join(out)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero when the committed settings.xml is stale",
    )
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = SETTINGS_PATH.read_text(encoding="utf-8")
        if current != rendered:
            print(
                "resources/settings/settings.xml is out of date; "
                "run python3 tools/gen_settings.py",
                file=sys.stderr,
            )
            return 1
        print("settings.xml is up to date")
        return 0

    SETTINGS_PATH.write_text(rendered, encoding="utf-8")
    print(f"wrote {SETTINGS_PATH.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
